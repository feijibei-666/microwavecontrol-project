#include "lcd.h"
#include "delay.h"

#define LCD_RS_PORT     GPIOB
#define LCD_RS_PIN      GPIO_Pin_7
#define LCD_RST_PORT    GPIOB
#define LCD_RST_PIN     GPIO_Pin_8
#define LCD_CS_PORT     GPIOB
#define LCD_CS_PIN      GPIO_Pin_9

#define RS_H()          GPIO_SetBits(LCD_RS_PORT, LCD_RS_PIN)
#define RS_L()          GPIO_ResetBits(LCD_RS_PORT, LCD_RS_PIN)
#define RST_H()         GPIO_SetBits(LCD_RST_PORT, LCD_RST_PIN)
#define RST_L()         GPIO_ResetBits(LCD_RST_PORT, LCD_RST_PIN)
#define CS_H()          GPIO_SetBits(LCD_CS_PORT, LCD_CS_PIN)
#define CS_L()          GPIO_ResetBits(LCD_CS_PORT, LCD_CS_PIN)

/* 72 MHz / 8 = 9 MHz. Reduce this if long jumper wires are unreliable. */
#ifndef LCD_SPI_PRESCALER
#define LCD_SPI_PRESCALER SPI_BaudRatePrescaler_8
#endif
#define LCD_TRANSFER_TIMEOUT_MS  50
#define LCD_WAIT_SPIN_LIMIT      1000000UL
#define LCD_X_OFFSET             0
#define LCD_Y_OFFSET             0

#define CMD_SWRESET     0x01
#define CMD_SLPOUT      0x11
#define CMD_NORON       0x13
#define CMD_INVOFF      0x20
#define CMD_INVON       0x21
#define CMD_DISPON      0x29
#define CMD_CASET       0x2A
#define CMD_RASET       0x2B
#define CMD_RAMWR       0x2C
#define CMD_MADCTL      0x36
#define CMD_COLMOD      0x3A

volatile uint32_t lcd_fault_code = LCD_FAULT_NONE;
static uint8_t dma_line[LCD_W * 2];
static const uint8_t LCD_F8x16[][16];

static void LCD_Fault(uint32_t code)
{
    lcd_fault_code = code;
    SPI_I2S_DMACmd(SPI1, SPI_I2S_DMAReq_Tx, DISABLE);
    DMA_Cmd(DMA1_Channel3, DISABLE);
    DMA_ClearFlag(DMA1_FLAG_GL3);
    SPI_Cmd(SPI1, DISABLE);
    CS_H();
}

static uint8_t LCD_WaitSPI(uint16_t flag, FlagStatus expected)
{
    uint32_t start = delay_millis();
    uint32_t spins = LCD_WAIT_SPIN_LIMIT;

    while (SPI_I2S_GetFlagStatus(SPI1, flag) != expected)
    {
        if (((uint32_t)(delay_millis() - start) >= LCD_TRANSFER_TIMEOUT_MS) ||
            (--spins == 0))
        {
            LCD_Fault(LCD_FAULT_SPI_TIMEOUT);
            return 0;
        }
    }
    return 1;
}

static void LCD_GPIOInit(void)
{
    GPIO_InitTypeDef gpio;
    SPI_InitTypeDef spi;
    DMA_InitTypeDef dma;

    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOA | RCC_APB2Periph_GPIOB |
                          RCC_APB2Periph_SPI1, ENABLE);
    RCC_AHBPeriphClockCmd(RCC_AHBPeriph_DMA1, ENABLE);
    gpio.GPIO_Pin = GPIO_Pin_5 | GPIO_Pin_7;
    gpio.GPIO_Mode = GPIO_Mode_AF_PP;
    gpio.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_Init(GPIOA, &gpio);
    gpio.GPIO_Pin = LCD_RS_PIN | LCD_RST_PIN | LCD_CS_PIN;
    gpio.GPIO_Mode = GPIO_Mode_Out_PP;
    GPIO_Init(GPIOB, &gpio);
    CS_H();
    RS_H();
    RST_H();

    SPI_I2S_DeInit(SPI1);
    SPI_StructInit(&spi);
    spi.SPI_Direction = SPI_Direction_1Line_Tx;
    spi.SPI_Mode = SPI_Mode_Master;
    spi.SPI_DataSize = SPI_DataSize_8b;
    spi.SPI_CPOL = SPI_CPOL_High;
    spi.SPI_CPHA = SPI_CPHA_2Edge;
    spi.SPI_NSS = SPI_NSS_Soft;
    spi.SPI_BaudRatePrescaler = LCD_SPI_PRESCALER;
    spi.SPI_FirstBit = SPI_FirstBit_MSB;
    SPI_Init(SPI1, &spi);
    SPI_NSSInternalSoftwareConfig(SPI1, SPI_NSSInternalSoft_Set);
    SPI_Cmd(SPI1, ENABLE);

    DMA_DeInit(DMA1_Channel3);
    DMA_StructInit(&dma);
    dma.DMA_PeripheralBaseAddr = (uint32_t)&SPI1->DR;
    dma.DMA_MemoryBaseAddr = (uint32_t)dma_line;
    dma.DMA_DIR = DMA_DIR_PeripheralDST;
    dma.DMA_BufferSize = sizeof(dma_line);
    dma.DMA_PeripheralInc = DMA_PeripheralInc_Disable;
    dma.DMA_MemoryInc = DMA_MemoryInc_Enable;
    dma.DMA_PeripheralDataSize = DMA_PeripheralDataSize_Byte;
    dma.DMA_MemoryDataSize = DMA_MemoryDataSize_Byte;
    dma.DMA_Mode = DMA_Mode_Normal;
    dma.DMA_Priority = DMA_Priority_Low;
    dma.DMA_M2M = DMA_M2M_Disable;
    DMA_Init(DMA1_Channel3, &dma);
    DMA_ClearFlag(DMA1_FLAG_GL3);
}

static void LCD_WriteByte(uint8_t data)
{
    if ((lcd_fault_code != LCD_FAULT_NONE) ||
        !LCD_WaitSPI(SPI_I2S_FLAG_TXE, SET))
    {
        return;
    }
    SPI_I2S_SendData(SPI1, data);
    if (!LCD_WaitSPI(SPI_I2S_FLAG_TXE, SET))
    {
        return;
    }
    LCD_WaitSPI(SPI_I2S_FLAG_BSY, RESET);
}

static void LCD_WriteCmd(uint8_t cmd)
{
    if (lcd_fault_code != LCD_FAULT_NONE) return;
    CS_L();
    RS_L();
    LCD_WriteByte(cmd);
    CS_H();
}

static void LCD_WriteData(uint8_t data)
{
    if (lcd_fault_code != LCD_FAULT_NONE) return;
    CS_L();
    RS_H();
    LCD_WriteByte(data);
    CS_H();
}

static void LCD_SetWindow(uint16_t x, uint16_t y, uint16_t width, uint16_t height)
{
    uint16_t x0 = x + LCD_X_OFFSET;
    uint16_t x1 = x + width - 1 + LCD_X_OFFSET;
    uint16_t y0 = y + LCD_Y_OFFSET;
    uint16_t y1 = y + height - 1 + LCD_Y_OFFSET;

    LCD_WriteCmd(CMD_CASET);
    LCD_WriteData((uint8_t)(x0 >> 8)); LCD_WriteData((uint8_t)x0);
    LCD_WriteData((uint8_t)(x1 >> 8)); LCD_WriteData((uint8_t)x1);
    LCD_WriteCmd(CMD_RASET);
    LCD_WriteData((uint8_t)(y0 >> 8)); LCD_WriteData((uint8_t)y0);
    LCD_WriteData((uint8_t)(y1 >> 8)); LCD_WriteData((uint8_t)y1);
    LCD_WriteCmd(CMD_RAMWR);
}


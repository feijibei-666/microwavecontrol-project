void LCD_Init(void)
{
    lcd_fault_code = LCD_FAULT_NONE;
    LCD_GPIOInit();
    RST_H(); delay_ms(10);
    RST_L(); delay_ms(10);
    RST_H(); delay_ms(120);
    LCD_InitSequence();
    LCD_Clear(LCD_BLACK);
}

/* DMA reads a single row from the small byte-order conversion buffer. The
 * caller holds CS/DC stable until the last SPI bit physically leaves the pin. */
static uint8_t LCD_SendLine(uint16_t width)
{
    uint32_t start = delay_millis();
    uint32_t spins = LCD_WAIT_SPIN_LIMIT;

    if (lcd_fault_code != LCD_FAULT_NONE) return 0;
    DMA_Cmd(DMA1_Channel3, DISABLE);
    DMA_ClearFlag(DMA1_FLAG_GL3);
    DMA_SetCurrDataCounter(DMA1_Channel3, (uint16_t)(width * 2));
    SPI_I2S_DMACmd(SPI1, SPI_I2S_DMAReq_Tx, ENABLE);
    DMA_Cmd(DMA1_Channel3, ENABLE);
    while (DMA_GetFlagStatus(DMA1_FLAG_TC3) == RESET)
    {
        if (DMA_GetFlagStatus(DMA1_FLAG_TE3) != RESET)
        {
            LCD_Fault(LCD_FAULT_DMA_TRANSFER);
            return 0;
        }
        if (((uint32_t)(delay_millis() - start) >= LCD_TRANSFER_TIMEOUT_MS) ||
            (--spins == 0))
        {
            LCD_Fault(LCD_FAULT_DMA_TIMEOUT);
            return 0;
        }
    }
    SPI_I2S_DMACmd(SPI1, SPI_I2S_DMAReq_Tx, DISABLE);
    DMA_Cmd(DMA1_Channel3, DISABLE);
    DMA_ClearFlag(DMA1_FLAG_GL3);
    if (!LCD_WaitSPI(SPI_I2S_FLAG_TXE, SET)) return 0;
    return LCD_WaitSPI(SPI_I2S_FLAG_BSY, RESET);
}

void LCD_Blit(uint16_t x, uint16_t y, uint16_t width, uint16_t height,
              const uint16_t *pixels)
{
    uint16_t source_width = width;
    uint16_t row, col, value;
    const uint16_t *source;

    if ((pixels == 0) || (x >= LCD_W) || (y >= LCD_H) ||
        (width == 0) || (height == 0) || (lcd_fault_code != LCD_FAULT_NONE)) return;
    if (width > LCD_W - x) width = (uint16_t)(LCD_W - x);
    if (height > LCD_H - y) height = (uint16_t)(LCD_H - y);
    LCD_SetWindow(x, y, width, height);
    if (lcd_fault_code != LCD_FAULT_NONE) return;
    CS_L(); RS_H();
    for (row = 0; row < height; row++)
    {
        source = pixels + (uint32_t)row * source_width;
        for (col = 0; col < width; col++)
        {
            value = source[col];
            dma_line[col * 2] = (uint8_t)(value >> 8);
            dma_line[col * 2 + 1] = (uint8_t)value;
        }
        if (!LCD_SendLine(width)) return;
    }
    CS_H();
}

void LCD_Fill(uint16_t x, uint16_t y, uint16_t width, uint16_t height, uint16_t color)
{
    uint16_t col, row;

    if ((x >= LCD_W) || (y >= LCD_H) || (width == 0) || (height == 0) ||
        (lcd_fault_code != LCD_FAULT_NONE)) return;
    if (width > LCD_W - x) width = (uint16_t)(LCD_W - x);
    if (height > LCD_H - y) height = (uint16_t)(LCD_H - y);
    for (col = 0; col < width; col++)
    {
        dma_line[col * 2] = (uint8_t)(color >> 8);
        dma_line[col * 2 + 1] = (uint8_t)color;
    }
    LCD_SetWindow(x, y, width, height);
    if (lcd_fault_code != LCD_FAULT_NONE) return;
    CS_L(); RS_H();
    for (row = 0; row < height; row++)
    {
        if (!LCD_SendLine(width)) return;
    }
    CS_H();
}

void LCD_Clear(uint16_t color)
{
    LCD_Fill(0, 0, LCD_W, LCD_H, color);
}

void LCD_DrawPoint(uint16_t x, uint16_t y, uint16_t color)
{
    LCD_Blit(x, y, 1, 1, &color);
}

uint8_t LCD_FontColumn(char ch, uint8_t column, uint8_t half)
{
    if ((ch < ' ') || (ch > '~') || (column >= 8) || (half >= 2)) return 0;
    return LCD_F8x16[(uint8_t)(ch - ' ')][column + half * 8];
}

void LCD_ShowChar(uint16_t x, uint16_t y, char ch, uint16_t fore, uint16_t back)
{
    uint16_t glyph[8 * 16];
    uint8_t i, j, bits;

    if ((x >= LCD_W) || (y >= LCD_H) || (LCD_W - x < 8) || (LCD_H - y < 16)) return;
    for (j = 0; j < 16; j++)
    {
        for (i = 0; i < 8; i++)
        {
            bits = LCD_FontColumn(ch, i, (uint8_t)(j / 8));
            glyph[j * 8 + i] = ((bits >> (j & 7)) & 1) ? fore : back;
        }
    }
    LCD_Blit(x, y, 8, 16, glyph);
}

void LCD_ShowString(uint16_t x, uint16_t y, const char *str, uint16_t fore, uint16_t back)
{
    if (str == 0) return;
    while ((*str != '\0') && (y <= LCD_H - 16))
    {
        LCD_ShowChar(x, y, *str++, fore, back);
        x += 8;
        if (x > LCD_W - 8)
        {
            x = 0;
            y += 16;
        }
    }
}

void LCD_ShowStringCenter(uint16_t y, const char *str, uint16_t fore, uint16_t back)
{
    uint16_t len = 0;
    if (str == 0) return;
    while (str[len] != '\0') len++;
    LCD_ShowString((len >= LCD_W / 8) ? 0 : (uint16_t)((LCD_W - len * 8) / 2),
                   y, str, fore, back);
}


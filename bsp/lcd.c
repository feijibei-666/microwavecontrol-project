#include "lcd.h"
#include "delay.h"

/* ---------------- 引脚定义（软件 SPI） ---------------- */
#define LCD_CLK_PORT    GPIOA
#define LCD_CLK_PIN     GPIO_Pin_5
#define LCD_SDA_PORT    GPIOA
#define LCD_SDA_PIN     GPIO_Pin_7
#define LCD_RS_PORT     GPIOB
#define LCD_RS_PIN      GPIO_Pin_7
#define LCD_RST_PORT    GPIOB
#define LCD_RST_PIN     GPIO_Pin_8
#define LCD_CS_PORT     GPIOB
#define LCD_CS_PIN      GPIO_Pin_9

#define CLK_H()     GPIO_SetBits(LCD_CLK_PORT, LCD_CLK_PIN)
#define CLK_L()     GPIO_ResetBits(LCD_CLK_PORT, LCD_CLK_PIN)
#define SDA_H()     GPIO_SetBits(LCD_SDA_PORT, LCD_SDA_PIN)
#define SDA_L()     GPIO_ResetBits(LCD_SDA_PORT, LCD_SDA_PIN)
#define RS_H()      GPIO_SetBits(LCD_RS_PORT, LCD_RS_PIN)
#define RS_L()      GPIO_ResetBits(LCD_RS_PORT, LCD_RS_PIN)
#define RST_H()     GPIO_SetBits(LCD_RST_PORT, LCD_RST_PIN)
#define RST_L()     GPIO_ResetBits(LCD_RST_PORT, LCD_RST_PIN)
#define CS_H()      GPIO_SetBits(LCD_CS_PORT, LCD_CS_PIN)
#define CS_L()      GPIO_ResetBits(LCD_CS_PORT, LCD_CS_PIN)

/* ST7735 命令 */
#define CMD_SWRESET     0x01
#define CMD_SLPOUT      0x11
#define CMD_NORON       0x13
#define CMD_INVOFF      0x20
#define CMD_INVON       0x21
#define CMD_DISPON      0x29
#define CMD_CASET       0x2A
#define CMD_RASET       0x2B
#define CMD_RAMWR       0x2C
#define CMD_MADCTL      0x36
#define CMD_COLMOD      0x3A

/* 显示窗口相对面板的偏移：若图像整体偏移，可调整这两个值 */
#define LCD_X_OFFSET    0
#define LCD_Y_OFFSET    0

/* 8x16 ASCII 字库，定义见文件末尾 */
static const uint8_t LCD_F8x16[][16];

static void LCD_GPIOInit(void);
static void LCD_WriteByte(uint8_t data);
static void LCD_WriteCmd(uint8_t cmd);
static void LCD_WriteData(uint8_t data);
static void LCD_SetWindow(uint16_t x, uint16_t y, uint16_t width, uint16_t height);
static void LCD_InitSequence(void);

/* ---------------- 低层：软件 SPI ---------------- */
static void LCD_GPIOInit(void)
{
    GPIO_InitTypeDef GPIO_InitStructure;

    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOA | RCC_APB2Periph_GPIOB, ENABLE);

    GPIO_InitStructure.GPIO_Mode  = GPIO_Mode_Out_PP;
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz;

    GPIO_InitStructure.GPIO_Pin = LCD_CLK_PIN | LCD_SDA_PIN;
    GPIO_Init(GPIOA, &GPIO_InitStructure);

    GPIO_InitStructure.GPIO_Pin = LCD_RS_PIN | LCD_RST_PIN | LCD_CS_PIN;
    GPIO_Init(GPIOB, &GPIO_InitStructure);

    CS_H();
    CLK_H();
}

/* 高位在前，时钟上升沿采样 */
static void LCD_WriteByte(uint8_t data)
{
    uint8_t i;

    for (i = 0; i < 8; i++)
    {
        CLK_L();
        if (data & 0x80)
        {
            SDA_H();
        }
        else
        {
            SDA_L();
        }
        data <<= 1;
        CLK_H();
    }
}

static void LCD_WriteCmd(uint8_t cmd)
{
    CS_L();
    RS_L();
    LCD_WriteByte(cmd);
    CS_H();
}

static void LCD_WriteData(uint8_t data)
{
    CS_L();
    RS_H();
    LCD_WriteByte(data);
    CS_H();
}

/* 设置显示窗口并准备写显存 */
static void LCD_SetWindow(uint16_t x, uint16_t y, uint16_t width, uint16_t height)
{
    uint16_t x0 = x + LCD_X_OFFSET;
    uint16_t x1 = x + width - 1 + LCD_X_OFFSET;
    uint16_t y0 = y + LCD_Y_OFFSET;
    uint16_t y1 = y + height - 1 + LCD_Y_OFFSET;

    LCD_WriteCmd(CMD_CASET);
    LCD_WriteData(x0 >> 8);
    LCD_WriteData(x0 & 0xFF);
    LCD_WriteData(x1 >> 8);
    LCD_WriteData(x1 & 0xFF);

    LCD_WriteCmd(CMD_RASET);
    LCD_WriteData(y0 >> 8);
    LCD_WriteData(y0 & 0xFF);
    LCD_WriteData(y1 >> 8);
    LCD_WriteData(y1 & 0xFF);

    LCD_WriteCmd(CMD_RAMWR);
}

/* ---------------- ST7735 初始化 ---------------- */
static void LCD_InitSequence(void)
{
    LCD_WriteCmd(CMD_SWRESET);
    delay_ms(120);
    LCD_WriteCmd(CMD_SLPOUT);
    delay_ms(120);

    LCD_WriteCmd(0xB1);                 /* 帧率控制 */
    LCD_WriteData(0x01); LCD_WriteData(0x2C); LCD_WriteData(0x2D);
    LCD_WriteCmd(0xB2);
    LCD_WriteData(0x01); LCD_WriteData(0x2C); LCD_WriteData(0x2D);
    LCD_WriteCmd(0xB3);
    LCD_WriteData(0x01); LCD_WriteData(0x2C); LCD_WriteData(0x2D);
    LCD_WriteData(0x01); LCD_WriteData(0x2C); LCD_WriteData(0x2D);

    LCD_WriteCmd(0xB4);                 /* 反显控制 */
    LCD_WriteData(0x07);

    LCD_WriteCmd(0xC0);                 /* 电源控制 */
    LCD_WriteData(0xA2); LCD_WriteData(0x02); LCD_WriteData(0x84);
    LCD_WriteCmd(0xC1);
    LCD_WriteData(0xC5);
    LCD_WriteCmd(0xC2);
    LCD_WriteData(0x0A); LCD_WriteData(0x00);
    LCD_WriteCmd(0xC3);
    LCD_WriteData(0x8A); LCD_WriteData(0x2A);
    LCD_WriteCmd(0xC4);
    LCD_WriteData(0x8A); LCD_WriteData(0xEE);
    LCD_WriteCmd(0xC5);                 /* VCOM */
    LCD_WriteData(0x0E);

    LCD_WriteCmd(CMD_MADCTL);           /* 扫描方向：MX|MY|BGR */
    LCD_WriteData(0xC8);

    LCD_WriteCmd(CMD_COLMOD);           /* 16 位色 RGB565 */
    LCD_WriteData(0x05);

    LCD_WriteCmd(0xE0);                 /* 伽马校正 */
    LCD_WriteData(0x02); LCD_WriteData(0x1C); LCD_WriteData(0x07); LCD_WriteData(0x12);
    LCD_WriteData(0x37); LCD_WriteData(0x32); LCD_WriteData(0x29); LCD_WriteData(0x2D);
    LCD_WriteData(0x29); LCD_WriteData(0x25); LCD_WriteData(0x2B); LCD_WriteData(0x39);
    LCD_WriteData(0x00); LCD_WriteData(0x01); LCD_WriteData(0x03); LCD_WriteData(0x10);

    LCD_WriteCmd(0xE1);
    LCD_WriteData(0x03); LCD_WriteData(0x1D); LCD_WriteData(0x07); LCD_WriteData(0x06);
    LCD_WriteData(0x2E); LCD_WriteData(0x2C); LCD_WriteData(0x29); LCD_WriteData(0x2D);
    LCD_WriteData(0x2E); LCD_WriteData(0x2E); LCD_WriteData(0x37); LCD_WriteData(0x3F);
    LCD_WriteData(0x00); LCD_WriteData(0x00); LCD_WriteData(0x02); LCD_WriteData(0x10);

    LCD_WriteCmd(CMD_INVON);            /* 颜色异常时改为 CMD_INVOFF */
    LCD_WriteCmd(CMD_NORON);
    LCD_WriteCmd(CMD_DISPON);
    delay_ms(100);
}

void LCD_Init(void)
{
    LCD_GPIOInit();

    /* 硬件复位 */
    RST_H();
    delay_ms(10);
    RST_L();
    delay_ms(10);
    RST_H();
    delay_ms(120);

    LCD_InitSequence();
    LCD_Clear(LCD_BLACK);
}

/* ---------------- 绘图 ---------------- */
void LCD_Fill(uint16_t x, uint16_t y, uint16_t width, uint16_t height, uint16_t color)
{
    uint32_t i, total;

    if ((x >= LCD_W) || (y >= LCD_H) || (width == 0) || (height == 0))
    {
        return;
    }
    if (x + width > LCD_W)
    {
        width = LCD_W - x;
    }
    if (y + height > LCD_H)
    {
        height = LCD_H - y;
    }

    LCD_SetWindow(x, y, width, height);

    total = (uint32_t)width * height;
    CS_L();
    RS_H();
    for (i = 0; i < total; i++)
    {
        LCD_WriteByte(color >> 8);
        LCD_WriteByte((uint8_t)color);
    }
    CS_H();
}

void LCD_Clear(uint16_t color)
{
    LCD_Fill(0, 0, LCD_W, LCD_H, color);
}

void LCD_DrawPoint(uint16_t x, uint16_t y, uint16_t color)
{
    if ((x >= LCD_W) || (y >= LCD_H))
    {
        return;
    }

    LCD_SetWindow(x, y, 1, 1);
    CS_L();
    RS_H();
    LCD_WriteByte(color >> 8);
    LCD_WriteByte((uint8_t)color);
    CS_H();
}

/* 显示一个 8x16 的 ASCII 字符 */
void LCD_ShowChar(uint16_t x, uint16_t y, char ch, uint16_t fore, uint16_t back)
{
    uint8_t  i, j, data;
    uint16_t color;

    if ((ch < ' ') || (ch > '~'))
    {
        ch = ' ';
    }
    if ((x + 8 > LCD_W) || (y + 16 > LCD_H))
    {
        return;
    }

    LCD_SetWindow(x, y, 8, 16);

    CS_L();
    RS_H();
    for (j = 0; j < 16; j++)                    /* 行 */
    {
        for (i = 0; i < 8; i++)                 /* 列 */
        {
            data  = LCD_F8x16[(uint8_t)(ch - ' ')][(j < 8) ? i : (i + 8)];
            color = ((data >> (j & 0x07)) & 0x01) ? fore : back;
            LCD_WriteByte(color >> 8);
            LCD_WriteByte((uint8_t)color);
        }
    }
    CS_H();
}

/* 显示字符串，超出右边界自动换行 */
void LCD_ShowString(uint16_t x, uint16_t y, const char *str, uint16_t fore, uint16_t back)
{
    while (*str != '\0')
    {
        LCD_ShowChar(x, y, *str, fore, back);
        x += 8;
        str++;
        if (x + 8 > LCD_W)
        {
            x = 0;
            y += 16;
        }
    }
}

/* 以 y 为起始行、水平居中显示字符串 */
void LCD_ShowStringCenter(uint16_t y, const char *str, uint16_t fore, uint16_t back)
{
    uint16_t len = 0;
    uint16_t x;

    while (str[len] != '\0')
    {
        len++;
    }

    if (len * 8 >= LCD_W)
    {
        x = 0;
    }
    else
    {
        x = (LCD_W - len * 8) / 2;
    }

    LCD_ShowString(x, y, str, fore, back);
}

